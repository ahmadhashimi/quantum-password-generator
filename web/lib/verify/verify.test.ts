import { describe, expect, it } from "vitest";

import vectors from "@/tests/vectors/receipts.json";

import { selectWinners } from "./draws";
import { fromHex } from "./encoding";
import { canonicalize, parseJson } from "./json";
import { type KeySet, verifyReceiptText } from "./verify";

type Case = { name: string; text: string; valid: boolean; canonical: string | null; value?: string; salt?: string;
              entries?: string[] };
const cases = vectors.cases as Case[];
const keys = vectors.keys as KeySet;

describe("cross-language receipt vectors (generated by the Python backend)", () => {
  it.each(cases.map((c) => [c.name, c] as const))("%s", (_name, c) => {
    const r = verifyReceiptText(c.text, keys, {
      ...(c.value !== undefined ? { value: c.value } : {}),
      ...(c.salt !== undefined ? { salt: c.salt } : {}),
      ...(c.entries !== undefined ? { entries: c.entries } : {}),
    });
    expect(r.valid, JSON.stringify(r.checks)).toBe(c.valid);
    if (c.valid) {
      expect(r.canonical).toBe(c.canonical); // byte-exact with Python's canonical JSON, floats included
      expect(r.signatures).toEqual({ ed25519: true, "ml-dsa-65": true });
    }
  });

  it("rejects revoked and mislabelled key sets", () => {
    const text = (cases[0] as Case).text;
    expect(verifyReceiptText(text, vectors.revoked_keys as KeySet).valid).toBe(false);
    const mis = verifyReceiptText(text, vectors.mislabelled_keys as KeySet);
    expect(mis.valid).toBe(false);
    expect(mis.checks.find((x) => x.id === "key")?.detail).toMatch(/mislabelled/);
  });

  it("recomputes the published draw exactly like Python's qpg-select/1", () => {
    const { seed_hex, winners, entries } = vectors.draw;
    expect(selectWinners(fromHex(seed_hex), entries.length, winners.length)).toEqual(winners);
  });
});

describe("lossless JSON", () => {
  it("keeps number lexemes and sorts keys by code point", () => {
    const v = parseJson('{"b":256.0,"a":1e-07,"\\ud83c\\udf89":[true,null],"\\uff21":"x"}');
    expect(canonicalize(v)).toBe('{"a":1e-07,"b":256.0,"Ａ":"x","🎉":[true,null]}');
  });

  it.each([
    ['{"a":1,"a":2}', /Duplicate key/],
    ['{"a":"\\ud800"}', /Lone surrogate/],
    ["[1,]", /Unexpected token/],
    ['{"a":01}', /Expected/],
    ["1 2", /Trailing/],
    ["[".repeat(40) + "]".repeat(40), /too deeply/],
  ])("rejects %s", (text, err) => {
    expect(() => parseJson(text)).toThrow(err);
  });

  it("never throws from verifyReceiptText on garbage", () => {
    for (const junk of ["", "null", "[]", '{"payload":5}', '{"payload":{"version":"qpg-receipt/2"}}', "\u0000"]) {
      expect(verifyReceiptText(junk, keys).valid).toBe(false);
    }
  });
});

describe("lossless serialisation", () => {
  it("round-trips receipts byte-exactly, pretty or compact", async () => {
    const { losslessField, stringifyLossless } = await import("./json");
    const c = cases.find((x) => x.name.startsWith("random bytes")) as Case;
    const tree = parseJson(c.text);
    expect(stringifyLossless(tree)).toBe(c.text);
    const pretty = stringifyLossless(tree, 2);
    expect(pretty).toContain('"entropy_bits": 256.0');
    expect(verifyReceiptText(pretty, keys).valid).toBe(true);
    expect(losslessField(JSON.stringify({ a: 1 }).replace("1", '{"x":2.50}'), "a")).toBe('{"x":2.50}');
  });
});
