import { Binary, KeyRound, RefreshCw, Text } from "lucide-react";
import { type FormEvent, type KeyboardEvent, type ReactNode, useCallback, useEffect, useId, useRef, useState } from "react";

import { ProvenanceBadge } from "@/components/receipts/ProvenanceBadge";
import { ReceiptCard } from "@/components/receipts/ReceiptCard";
import { EntropyMeter } from "@/components/secrets/EntropyMeter";
import { SecretDisplay } from "@/components/secrets/SecretDisplay";
import { Button, Callout, Card, CardBody, CardHeader, Field, Tabs, Toggle } from "@/components/ui";
import { apiWithText, type TokenGetter } from "@/lib/api/client";
import { PassphraseResponse, PasswordResponse, type Provenance, RandomResponse, type Receipt } from "@/lib/api/schemas";
import { useAppAuth } from "@/lib/auth/client";
import { losslessField } from "@/lib/verify/json";

import { RangeField, SELECT_CLASS, Segmented } from "./controls";
import { ProvenanceNotice } from "./ProvenanceNotice";
import { type SecretKind, useSessionHistory } from "./SessionHistory";
import { isAbortError, type ShownError, toShownError } from "./util";

type Mode = SecretKind;
type Separator = "-" | "_" | "." | " " | "";
type ByteSize = 16 | 32 | 64;

interface Settings {
  mode: Mode;
  length: number;
  upper: boolean;
  lower: boolean;
  digits: boolean;
  symbols: boolean;
  excludeAmbiguous: boolean;
  requireEach: boolean;
  words: number;
  separator: Separator;
  capitalize: boolean;
  addNumber: boolean;
  bytes: ByteSize;
  signed: boolean;
}

const DEFAULTS: Settings = {
  mode: "password", length: 24, upper: true, lower: true, digits: true, symbols: true, excludeAmbiguous: false,
  requireEach: true, words: 6, separator: "-", capitalize: false, addNumber: false, bytes: 32, signed: true,
};

// Icons are dropped below `sm`: three labelled tabs with icons do not fit a 375px card.
const MODES = [
  { value: "password", label: "Password", icon: <KeyRound aria-hidden className="hidden sm:block" /> },
  { value: "passphrase", label: "Passphrase", icon: <Text aria-hidden className="hidden sm:block" /> },
  { value: "random", label: "Random key", icon: <Binary aria-hidden className="hidden sm:block" /> },
] as const satisfies readonly { value: Mode; label: string; icon: ReactNode }[];

const NOUN: Record<Mode, string> = { password: "password", passphrase: "passphrase", random: "key" };
const SEPARATORS: { value: Separator; label: string }[] = [
  { value: "-", label: "Dash (-)" }, { value: "_", label: "Underscore (_)" }, { value: ".", label: "Dot (.)" },
  { value: " ", label: "Space" }, { value: "", label: "None" },
];
const BYTE_OPTIONS = [
  { value: 16, label: "16 bytes", hint: "128 bits" },
  { value: 32, label: "32 bytes", hint: "256 bits" },
  { value: 64, label: "64 bytes", hint: "512 bits" },
] as const;

interface Draft {
  kind: Mode;
  value: string;
  entropyBits: number;
  provenance: Provenance;
  receipt: Receipt | null;
  /** Lossless JSON of the receipt exactly as received (numbers such as 128.0 intact), or null if unreadable. */
  receiptText: string | null;
  salt: string | undefined;
}

type Generated = Draft & { seq: number };

interface WithReceipt {
  provenance: Provenance;
  receipt?: Receipt | undefined;
  receipt_salt?: string | undefined;
}

function toDraft(kind: Mode, value: string, entropyBits: number, data: WithReceipt, text: string): Draft {
  let receiptText: string | null = null;
  if (data.receipt) {
    try {
      receiptText = losslessField(text, "receipt");
    } catch {
      // Reported as an unreadable receipt below; the generated value is still shown.
    }
  }
  return { kind, value, entropyBits, provenance: data.provenance, receipt: data.receipt ?? null, receiptText,
           salt: data.receipt_salt };
}

/** The secret is generated by the backend and only ever travels in the response body, never in the request. */
async function fetchDraft(s: Settings, getToken: TokenGetter, signal: AbortSignal): Promise<Draft> {
  if (s.mode === "password") {
    const { data, text } = await apiWithText("/api/v2/password", {
      schema: PasswordResponse, getToken, signal,
      query: { length: s.length, upper: s.upper, lower: s.lower, digits: s.digits, symbols: s.symbols,
               exclude_ambiguous: s.excludeAmbiguous, require_each: s.requireEach, receipt: s.signed },
    });
    return toDraft("password", data.password, data.entropy_bits, data, text);
  }
  if (s.mode === "passphrase") {
    const { data, text } = await apiWithText("/api/v2/passphrase", {
      schema: PassphraseResponse, getToken, signal,
      query: { words: s.words, separator: s.separator, capitalize: s.capitalize, add_number: s.addNumber,
               receipt: s.signed },
    });
    return toDraft("passphrase", data.passphrase, data.entropy_bits, data, text);
  }
  const { data, text } = await apiWithText("/api/v2/random", {
    schema: RandomResponse, getToken, signal, query: { bytes: s.bytes, receipt: s.signed },
  });
  return toDraft("random", data.hex, data.bytes * 8, data, text);
}

const PLACEHOLDER: Record<Mode, string> = {
  password: "Press Generate to create a password",
  passphrase: "Press Generate to create a passphrase",
  random: "Press Generate to create a random key",
};

function Evidence({ provenance }: { provenance: Provenance }) {
  const screening = provenance.health?.["sp800_90b_style"] ?? provenance.health?.["sp800_90b"];
  return (
    <p className="text-xs text-muted">
      Sources{screening && screening !== "n/a" ? " and health screening" : ""} are reported by this server
      (operator-asserted). Independent quantum evidence: none available.
      {screening && screening !== "n/a" && (
        <> Screening is SP 800-90B-style RCT/APT (not a NIST validation): {screening}.</>
      )}
    </p>
  );
}

function Result({ result }: { result: Generated }) {
  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <ProvenanceBadge provenance={result.provenance} />
      </div>
      <EntropyMeter bits={result.entropyBits} />
      <ProvenanceNotice provenance={result.provenance} />
      <Evidence provenance={result.provenance} />
      {result.receipt && result.receiptText && (
        <ReceiptCard receipt={result.receipt} receiptText={result.receiptText} salt={result.salt} />
      )}
      {result.receipt && !result.receiptText && (
        <Callout tone="warning" title="Receipt not offered">
          The receipt in the response could not be read exactly as sent, so it is not offered for download or
          verification. Generate again to get a fresh one.
        </Callout>
      )}
    </div>
  );
}

export function Generator() {
  const { getToken } = useAppAuth();
  const history = useSessionHistory();
  const hintId = useId();
  const panelId = useId();
  const [s, setS] = useState<Settings>(DEFAULTS);
  const [result, setResult] = useState<Generated | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<ShownError | null>(null);
  const abortRef = useRef<AbortController | null>(null);
  const seq = useRef(0);

  const patch = useCallback((p: Partial<Settings>) => setS((prev) => ({ ...prev, ...p })), []);
  const noCharset = s.mode === "password" && !(s.upper || s.lower || s.digits || s.symbols);

  useEffect(() => () => abortRef.current?.abort(), []);

  const generate = async () => {
    if (noCharset || loading) return;
    const controller = new AbortController();
    abortRef.current = controller;
    setLoading(true);
    setError(null);
    try {
      const draft = await fetchDraft(s, getToken, controller.signal);
      if (controller.signal.aborted) return;
      setResult({ ...draft, seq: ++seq.current });
      history.add({ kind: draft.kind, value: draft.value, entropyBits: draft.entropyBits,
                    quantum: draft.provenance.quantum });
    } catch (e) {
      if (isAbortError(e) || controller.signal.aborted) return;
      setResult(null);
      setError(toShownError(e));
    } finally {
      if (abortRef.current === controller) {
        abortRef.current = null;
        setLoading(false);
      }
    }
  };

  const changeMode = (mode: Mode) => {
    if (mode === s.mode) return;
    abortRef.current?.abort();
    abortRef.current = null;
    setLoading(false);
    setResult(null);
    setError(null);
    patch({ mode });
  };

  const onSubmit = (e: FormEvent) => {
    e.preventDefault();
    void generate();
  };

  // Enter inside a slider or switch does not submit natively in every browser; make it consistent.
  const onKeyDown = (e: KeyboardEvent<HTMLFormElement>) => {
    if (e.key === "Enter" && !e.nativeEvent.isComposing && e.target instanceof HTMLInputElement) {
      e.preventDefault();
      void generate();
    }
  };

  const noun = NOUN[s.mode];
  return (
    <Card>
      <CardHeader icon={<KeyRound />} title="Generator"
                  description="Quantum-seeded when sources are available, always mixed with the OS CSPRNG." />
      <CardBody>
        <form onSubmit={onSubmit} onKeyDown={onKeyDown} noValidate className="space-y-6">
          <Tabs label="Secret type" value={s.mode} onChange={changeMode} options={[...MODES]} className="w-full"
                controls={panelId} />

          <div aria-busy={loading} className="space-y-4">
            <SecretDisplay value={result?.value ?? null} label={`Generated ${noun}`}
                           placeholder={loading ? "Generating…" : PLACEHOLDER[s.mode]} />
            <p role="status" className="sr-only">
              {result ? `${NOUN[result.kind]} number ${result.seq} generated. ${result.entropyBits.toFixed(0)} bits of entropy. ${
                result.provenance.quantum ? "Quantum-seeded." : "Not quantum."}` : ""}
            </p>
            {result && <Result result={result} />}
            {error && (
              <Callout tone="danger" role="alert" title="Could not generate">
                {error.message}
                {error.requestId && <span className="mt-1 block font-mono text-xs text-subtle">Request {error.requestId}</span>}
              </Callout>
            )}
          </div>

          <div id={panelId} role="tabpanel" aria-label={`${MODES.find((m) => m.value === s.mode)?.label} options`}
               className="space-y-5">
            {s.mode === "password" && (
              <>
                <RangeField label="Length" unit="characters" min={8} max={128} value={s.length}
                            onChange={(length) => patch({ length })} />
                <fieldset className="min-w-0 space-y-2">
                  <legend className="mb-2 text-sm font-medium text-fg">Character sets</legend>
                  <div className="grid gap-2 sm:grid-cols-2">
                    <Toggle label="Uppercase A–Z" checked={s.upper} onChange={(upper) => patch({ upper })} />
                    <Toggle label="Lowercase a–z" checked={s.lower} onChange={(lower) => patch({ lower })} />
                    <Toggle label="Digits 0–9" checked={s.digits} onChange={(digits) => patch({ digits })} />
                    <Toggle label="Symbols !@#$" checked={s.symbols} onChange={(symbols) => patch({ symbols })} />
                  </div>
                </fieldset>
                <div className="grid gap-2 sm:grid-cols-2">
                  <Toggle label="Exclude look-alikes" checked={s.excludeAmbiguous}
                          onChange={(excludeAmbiguous) => patch({ excludeAmbiguous })} />
                  <Toggle label="Require each set" checked={s.requireEach}
                          onChange={(requireEach) => patch({ requireEach })} />
                </div>
                <p className="text-xs text-subtle">
                  Look-alikes are characters such as 0, O, 1, l and I. Requiring each set guarantees at least one
                  character from every selected set.
                </p>
              </>
            )}

            {s.mode === "passphrase" && (
              <>
                <RangeField label="Words" unit="words" min={3} max={16} value={s.words}
                            onChange={(words) => patch({ words })} />
                <Field label="Separator">
                  {({ id, describedBy }) => (
                    <select id={id} aria-describedby={describedBy} className={SELECT_CLASS} value={s.separator}
                            onChange={(e) => {
                              const next = SEPARATORS.find((o) => o.value === e.target.value);
                              if (next) patch({ separator: next.value });
                            }}>
                      {SEPARATORS.map((o) => <option key={o.label} value={o.value}>{o.label}</option>)}
                    </select>
                  )}
                </Field>
                <div className="grid gap-2 sm:grid-cols-2">
                  <Toggle label="Capitalize words" checked={s.capitalize}
                          onChange={(capitalize) => patch({ capitalize })} />
                  <Toggle label="Add a number" checked={s.addNumber} onChange={(addNumber) => patch({ addNumber })} />
                </div>
              </>
            )}

            {s.mode === "random" && (
              <>
                <Segmented legend="Key size" value={s.bytes} options={[...BYTE_OPTIONS]}
                           onChange={(bytes) => patch({ bytes })} />
                <p className="text-xs text-subtle">Shown as lowercase hex, two characters per byte.</p>
              </>
            )}
          </div>

          <div className="space-y-2">
            <Toggle label="Attach signed receipt" checked={s.signed} onChange={(signed) => patch({ signed })} />
            <p className="text-xs text-subtle">
              The receipt records the sources and a salted commitment, never the value, and is signed with Ed25519
              and ML-DSA-65.
            </p>
          </div>

          <div className="space-y-2">
            <Button type="submit" size="lg" className="w-full" disabled={loading || noCharset}
                    aria-describedby={noCharset ? hintId : undefined}>
              <RefreshCw className={loading ? "size-4 animate-spin" : "size-4"} aria-hidden />
              {loading ? "Generating…" : `Generate ${noun}`}
            </Button>
            {noCharset && (
              <p id={hintId} role="alert" className="text-center text-xs text-danger">
                Select at least one character set to generate a password.
              </p>
            )}
          </div>
        </form>
      </CardBody>
    </Card>
  );
}
